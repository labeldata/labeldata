# 라목 — "식품…의 원료로 사용되는 등 그 자체로는 최종 소비자에게 제공되지
# 않는 식품". 이건 식품유형이 아니라 **그 제품이 무엇으로 쓰이는가** 라서
# 유형 이름으로는 가릴 수 없다. 라벨에 그렇게 적혀 있으면 그것을 근거로 본다 —
# 실제 도안에 "제조업소 등에서 제조가공하는 원료입니다" 가 인쇄된다.
#
# **이 신호는 조용해지는 쪽으로만 쓴다.** 잘못 걸려도 지금까지의 동작(아무 말
# 안 함)으로 돌아갈 뿐, 없는 지적을 만들지 않는다.
_INGREDIENT_USE_RE = re.compile(
    r'(제품\s*제조\s*용|제조\s*가공\s*하는\s*원료|원료\s*로\s*사용|원료용\s*제품)')

TARGET = 'target'
EXEMPT = 'exempt'
UNKNOWN = 'unknown'


def _squeeze(text: str) -> str:
    """비교할 때만 쓰는 형태. 호환 문자를 펼치고 공백·가운뎃점을 지운다."""
    if not text:
        return ''
    text = unicodedata.normalize('NFKC', str(text))
    return re.sub(r'[\s·ㆍ・]', '', text).strip()


_EXEMPT_SQUEEZED = {_squeeze(t): t for t in _EXEMPT_TYPES}
_TARGET_SQUEEZED = {_squeeze(t): t for t in _TARGET_TYPES}


def _label_text(label) -> str:
    """인쇄되는 문장들. 주의사항과 기타표시사항의 경계는 사람마다 다르다."""
    return ' '.join(str(getattr(label, f, '') or '')
                    for f in ('cautions', 'additional_info', 'prdlst_nm'))


def scope(label) -> tuple[str, str]:
    """
    (판정, 근거) 를 돌려준다. 판정은 TARGET · EXEMPT · UNKNOWN 셋 중 하나.

    **제외를 먼저 본다.** 대상 목록에 있는 유형이라도 제외에 걸리면 제외다.
    """
    if _INGREDIENT_USE_RE.search(_label_text(label)):
        return EXEMPT, '제품제조용 원료로 표시돼 있어 영양표시 제외 식품(별표 4 라목)에 해당합니다.'

    food_type = _squeeze(getattr(label, 'prdlst_dcnm', '') or '')
    if not food_type:
        return UNKNOWN, '식품유형이 비어 있어 영양표시 대상 여부를 가리지 못했습니다.'

    # 김치는 배추김치만 대상이다
    if '김치' in food_type:
        if _squeeze(_KIMCHI_TARGET) == food_type:
            return TARGET, '배추김치는 영양표시 대상 식품입니다.'
        return EXEMPT, '배추김치가 아닌 김치는 영양표시 제외 식품입니다.'

    if food_type in _EXEMPT_SQUEEZED:
        return EXEMPT, '식품유형 "%s" 은(는) 영양표시 제외 식품입니다.' % _EXEMPT_SQUEEZED[food_type]
    if food_type in _TARGET_SQUEEZED:
        return TARGET, '식품유형 "%s" 은(는) 영양표시 대상 식품입니다.' % _TARGET_SQUEEZED[food_type]

    return UNKNOWN, '식품유형 "%s" 은(는) 대상·제외 목록 어느 쪽에서도 찾지 못했습니다.' % (
        getattr(label, 'prdlst_dcnm', '') or '')
